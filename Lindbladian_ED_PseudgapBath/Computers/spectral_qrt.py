def alpha_func_eq14(r: float) -> float:
    """
    Note Eq. (14): Universal dimensionless thermal prefactor alpha(r) (for r < 2)[cite: 45, 73]:
        alpha(r) = (1 / ln 2) * (int_{0}{infty} : (x^{1-r} / ((1 + exp(x))(1 + exp(-x)))) dx)
                 = Gamma_E(2 - r) (1 - 2^r) zeta(1 - r) / ln 2

    Numerical Desingularization
    ---------------------------
    For 0 < r < 1, the factor x^{1-r} has an infinite derivative at x -> 0+.
    We substitute x = x_max * s^{1/p} with p = 2 - r, so that:
        x^{1-r} dx = (x_max^p / p) ds
    making the integrand completely smooth at s = 0 for all r in (-1, 1)[cite: 73].
    """
    ln2 = np.log(2.0)
    if np.isclose(r, 0.0):
        return 1.0

    p = 2.0 - r
    x_max = 50.0
    x_nodes = x_max * (_GL128_S ** (1.0 / p))
    jacobian_w = (x_max ** p / p) * _GL128_W
    emx = np.exp(-x_nodes)
    fermi_factor = emx / ((1.0 + emx) ** 2)
    return float(np.sum(fermi_factor * jacobian_w) / ln2)


def analytic_tilde_S0_eq14(T_S: float, Gamma0: float, GammaS0: float, r: float) -> float:
    """
    Note Eq. (14): Low-temperature asymptotic scaling formula at resonance (eps_d = 0)[cite: 45, 73]:
        tilde{S}_{Eq.14}(0) = (Gamma_{S,0} / Gamma_0) * (alpha(r) / T_S^r) * S(0)
    where S(0) = r ln 2.
    """
    S0_lowT = r * np.log(2.0)
    return float((GammaS0 / Gamma0) * (alpha_func_eq14(r) / (T_S ** r)) * S0_lowT)


def analytic_tilde_S0_eq12(T_S: float, Gamma0: float, GammaS0: float, r: float) -> float:
    """
    Note Eq. (12) evaluated at eps_d = 0 (weak-probe limit Gamma_S << Gamma(w),
    infinite bandwidths D, D_S -> infty, retaining the finite-T_S arctan argument)[cite: 45, 73]:
        tilde{S}_{Eq.12}(0) = (2 / pi) (Gamma_{S,0} / (Gamma_0 T_S^r)) *
            (int_{0}{infty} : (x^{1-r} / ((1 + exp(x))(1 + exp(-x)))) * arctan(tan(pi r / 2) + (x T_S)^{1-r} / Gamma_0) dx)
    Evaluated via the desingularizing substitution x = x_max * s^{1/(2-r)}[cite: 73].
    """
    tan_pr2 = np.tan(0.5 * np.pi * r)
    pref = (2.0 / np.pi) * (GammaS0 / (Gamma0 * (T_S ** r)))

    p = 2.0 - r
    x_max = 50.0
    x_nodes = x_max * (_GL128_S ** (1.0 / p))
    jacobian_w = (x_max ** p / p) * _GL128_W

    emx = np.exp(-x_nodes)
    fermi_factor = emx / ((1.0 + emx) ** 2)
    arg = tan_pr2 + ((x_nodes * T_S) ** (1.0 - r)) / Gamma0
    return float(pref * np.sum(fermi_factor * np.arctan(arg) * jacobian_w))


def analytic_two_bath_tilde_S_eps_d(
    eps_d: float | np.ndarray,
    T_S: float,
    Gamma0: float,
    GammaS0: float,
    r: float,
    D_PG: Optional[float] = 1.0,
    D_S: Optional[float] = 1.0,
    omega_ir_PG: float = 0.0,
    probe_shape_fn: Optional[Callable[[np.ndarray], np.ndarray]] = None,
    eps_max: Optional[float] = None,
) -> float | np.ndarray:
    """
    Exact two-bath continuum integral from Note Eqs. (9)-(11) integrated over eps_d' in [-eps_max, eps_d][cite: 45, 73]:
        tilde{S}_{exact}(eps_d) = -int_{-eps_max}{eps_d} : (dn_d(eps_d', T_S) / dT_S) deps_d'
            = -int_{-D_lim}{D_lim} : (df_S(w; T_S) / dT_S) * (Gamma_S(w) / (Gamma_{PG}(w) + Gamma_S(w)))
              * (1 / pi) [ arctan((eps_d - w + Sigma_{tot}(w)) / (Gamma_{PG}(w) + Gamma_S(w)))
                         - arctan((-eps_max - w + Sigma_{tot}(w)) / (Gamma_{PG}(w) + Gamma_S(w))) ] dw

    Physical Effects Retained Explicitly in This Function
    -----------------------------------------------------
    Unlike the idealized asymptotic formula Eq. (14) (which assumes Gamma_S -> 0, D -> infty,
    D_S -> infty, and T_S -> 0), this function retains all finite cutoffs and profiles:
      1. Full branching ratio Gamma_S(w) / (Gamma_{PG}(w) + Gamma_S(w)) and probe broadening
         +Gamma_S(w) inside the dot spectral width.
      2. Finite power-law bath bandwidth D_PG and finite Kramers-Kronig self-energy Sigma_{D_PG}(w).
      3. Explicit probe bath cutoff D_S (for a flat short band) or smooth frequency profile
         Gamma_S(w) = Gamma_{S,0} * probe_shape_fn(w) (e.g., Lorentzian 1 / (1 + (w / D_S)^2)).
      4. Finite gate-voltage integration lower bound -eps_max.
    """
    ed_arr = np.atleast_1d(np.asarray(eps_d, dtype=float))
    D_lim = D_S if D_S is not None else (D_PG if D_PG is not None else None)
    x_max = 45.0 if D_lim is None else min(45.0, 0.999 * D_lim / T_S)

    # Desingularize x -> 0+ via x = x_max * s^{1/p} with p = 2 - max(r, 0)
    p = 2.0 - max(r, 0.0)
    x_nodes = x_max * (_GL128_S ** (1.0 / p))
    dx_weights = (x_max / p) * (_GL128_S ** (1.0 / p - 1.0)) * _GL128_W

    emx = np.exp(-x_nodes)
    thermal_weight = x_nodes * emx / ((1.0 + emx) ** 2)

    def eval_branch_matrix(w_vec: np.ndarray) -> np.ndarray:
        if omega_ir_PG > 0.0:
            g_p = Gamma0 * ((w_vec * w_vec + omega_ir_PG * omega_ir_PG) ** (0.5 * r))
            D_use = D_PG if D_PG is not None else 1.0
            s_t = continuum_self_energy_ir_finite_D(w_vec, Gamma0, r, D_use, omega_ir_PG)
            if D_PG is not None:
                g_p = np.where(np.abs(w_vec) <= D_PG, g_p, 0.0)
        else:
            g_p = Gamma0 * (np.abs(w_vec) ** r)
            if D_PG is not None:
                g_p = np.where(np.abs(w_vec) <= D_PG, g_p, 0.0)
                s_t = continuum_self_energy_finite_D(w_vec, Gamma0, r, D_PG)
            else:
                s_t = continuum_self_energy_infinite_D(w_vec, Gamma0, r)

        if probe_shape_fn is not None:
            g_s = GammaS0 * np.asarray(probe_shape_fn(w_vec), dtype=float)
        else:
            g_s = np.full_like(w_vec, GammaS0)
        if D_S is not None:
            g_s = np.where(np.abs(w_vec) <= D_S, g_s, 0.0)

        g_tot = g_p + g_s
        branch = np.where(g_tot > 0.0, g_s / g_tot, 0.0)

        upper = np.arctan((ed_arr[:, None] - w_vec[None, :] + s_t[None, :]) / g_tot[None, :]) / np.pi
        if eps_max is None:
            return branch[None, :] * (0.5 + upper)
        lower = np.arctan((-eps_max - w_vec[None, :] + s_t[None, :]) / g_tot[None, :]) / np.pi
        return branch[None, :] * (upper - lower)

    diff_mat = eval_branch_matrix(-x_nodes * T_S) - eval_branch_matrix(x_nodes * T_S)
    res = diff_mat @ (thermal_weight * dx_weights)
    return res if np.ndim(eps_d) > 0 else float(res[0])