def bare_bath_hybridization_dl(bath: Bath, omega: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """
    Solve for the bare retarded self-energy Delta^R_{alpha;DL}(w) of a single discretized
    tight-binding bath decoupled from the dot (LDDL Eqs. 31a, 42b, 43)[cite: 5, 7, 73].

    Physical & Mathematical Procedure
    ---------------------------------
    For a discrete tight-binding mode q with on-site energy eps_q, dot-bath hopping v_q,
    and Lindblad damping rate gamma_q = lambda_q^{(1)} + lambda_q^{(2)}, the bare retarded
    Green's function of mode q is (LDDL Eq. 42b)[cite: 7]:
        g^R_{qq;DL}(w) = 1 / (w - eps_q + i gamma_q)
                       = (w - eps_q) / ((w - eps_q)^2 + gamma_q^2)
                         - i gamma_q / ((w - eps_q)^2 + gamma_q^2)

    Summing over all N_modes tight-binding modes in the bath yields the bare retarded
    hybridization function Delta^R_{alpha;DL}(w) = Sigma_{alpha;DL}(w) - i Gamma_{alpha;DL}(w)[cite: 5, 7, 73]:
        Sigma_{alpha;DL}(w) = Re Delta^R_{alpha;DL}(w)
                            = sum_{q=1}^{N_modes} : |v_q|^2 (w - eps_q) / ((w - eps_q)^2 + gamma_q^2)
        Gamma_{alpha;DL}(w) = -Im Delta^R_{alpha;DL}(w)
                            = sum_{q=1}^{N_modes} : |v_q|^2 gamma_q / ((w - eps_q)^2 + gamma_q^2)

    Parameters
    ----------
    bath : Bath
        Discretized tight-binding Bath object containing (epsilons, v, gammas)[cite: 71, 73].
    omega : np.ndarray, shape (N_w,)
        Frequency grid w at which to evaluate Sigma_{DL}(w) and Gamma_{DL}(w)[cite: 73].

    Returns
    -------
    re_delta : np.ndarray, shape (N_w,)
        Real part Sigma_{alpha;DL}(w) = Re Delta^R_{alpha;DL}(w) (discrete Kramers-Kronig shift)[cite: 73].
    gamma_dl : np.ndarray, shape (N_w,)
        Negative imaginary part Gamma_{alpha;DL}(w) = -Im Delta^R_{alpha;DL}(w) (broadened DOS)[cite: 7, 73].
    """
    w = np.asarray(omega, dtype=float)
    re_delta = np.zeros_like(w)
    gamma_dl = np.zeros_like(w)

    # Sum over the N_modes tight-binding modes in chunks of 1,000 to keep intermediate
    # 2D arrays (N_w x chunk_size) small in RAM even when N_modes = 10,000.
    chunk_size = 1000
    for start in range(0, bath.n_modes, chunk_size):
        end = min(bath.n_modes, start + chunk_size)
        diff = w[:, None] - bath.epsilons[None, start:end]
        gam = bath.gammas[None, start:end]
        v2 = (bath.v[None, start:end]) ** 2
        denom = diff * diff + gam * gam
        re_delta += np.sum(v2 * diff / denom, axis=1)
        gamma_dl += np.sum(v2 * gam / denom, axis=1)

    return re_delta, gamma_dl


def dot_spectral_function_dl_freq(
    solver: Any,
    eps_d: float,
    omega: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Compute the dressed dot retarded Green's function G^R_{dd;DL}(w) and dot spectral
    function A_{d;DL}(eps_d; w) directly in frequency space (LDDL Eqs. 17, 50a)[cite: 4, 9, 73].

    Physical & Mathematical Procedure
    ---------------------------------
    For the full quadratic tight-binding system (dot + discretized baths), LDDL Eq. (17)
    gives the M x M matrix retarded Green's function[cite: 4]:
        G^R_{DL}(w) = (w I - H + i Lambda^{(+)})^{-1}
    Because H has the star (arrowhead) geometry where bath modes couple only to the dot
    and Lambda^{(+)} = diag(0, gamma_q) is diagonal on the bath modes[cite: 4, 9], eliminating the
    bath blocks via the Schur complement (LDDL Eqs. 49-50a) yields the exact (d, d) component[cite: 9]:
        G^R_{dd;DL}(w) = 1 / (w - eps_d - sum_{alpha} : Delta^R_{alpha;DL}(w))
                       = 1 / (w - eps_d - Sigma_{tot;DL}(w) + i Gamma_{tot;DL}(w))
    and the dot spectral function is:
        A_{d;DL}(eps_d; w) = -(1 / pi) Im G^R_{dd;DL}(w)

    Parameters
    ----------
    solver : LyapunovSolver
        Solver holding the list of connected tight-binding Bath objects (`solver.baths`)[cite: 66, 73].
    eps_d : float
        Impurity energy level eps_d[cite: 73].
    omega : np.ndarray, shape (N_w,)
        Frequency grid w[cite: 73].

    Returns
    -------
    G_ret : np.ndarray (complex), shape (N_w,)
        Dressed retarded dot Green's function G^R_{dd;DL}(w)[cite: 9, 73].
    A_dl : np.ndarray (float), shape (N_w,)
        Dressed dot spectral function A_{d;DL}(eps_d; w)[cite: 8, 73].
    """
    w = np.asarray(omega, dtype=float)
    re_tot = np.zeros_like(w)
    im_tot = np.zeros_like(w)
    for b in solver.baths:
        re_b, gam_b = bare_bath_hybridization_dl(b, w)
        re_tot += re_b
        im_tot -= gam_b  # Im Delta^R = -Gamma

    G_ret = 1.0 / (w - eps_d - re_tot - 1j * im_tot)
    A_dl = -(1.0 / np.pi) * np.imag(G_ret)
    return G_ret, A_dl


def dot_retarded_gf_qrt_time(
    solver: Any,
    eps_d: float,
    t_grid: np.ndarray,
) -> np.ndarray:
    """
    Compute the real-time retarded dot Green's function G^R_{dd}(t) using the
    Fermionic Quantum Regression Theorem (LDDL Sec. II B Eqs. 13-17 & Appendix B)[cite: 4, 18, 19, 20, 73].

    Why the Fermionic QRT Has a Sign Flip (LDDL Appendix B)
    -------------------------------------------------------
    We want the two-time retarded anticommutator correlator in the steady state (LDDL Eq. 7a)[cite: 3]:
        G^R_{mn}(t) = -i theta(t) <{c_m(t), c_n^+(0)}>_{NESS}
                    = -i theta(t) tr_S( c_m rho_{c_n^+}(t) + c_m rho'_{c_n^+}(t) )
    where rho_C(0) = C rho_{NESS} and rho'_C(0) = rho_{NESS} C with C = c_n^+[cite: 3, 4].
    Because C = c_n^+ contains an ODD number of fermion operators, it anticommutes with
    the bath fermion operators r_alpha in the system-reservoir coupling H_{S,R} (LDDL Eq. B2)[cite: 4, 19].
    Tracking the Jordan-Wigner fermion parity string (-1)^{N_S} when tracing out the Markovian
    reservoir flips the sign (zeta = -1) of the "recycling" sandwich terms in the Lindblad
    master equation for rho_C(t) (LDDL Eq. 13 & Eq. B16)[cite: 4, 20]:
        d/dt rho_C(t) = -i [H, rho_C(t)] +
                        sum_{q=1}^{N} : lambda_q^{(1)} (-2 c_q rho_C(t) c_q^+ - {c_q^+ c_q, rho_C(t)}) +
                        sum_{q=1}^{N} : lambda_q^{(2)} (-2 c_q^+ rho_C(t) c_q - {c_q c_q^+, rho_C(t)})

    Because of this zeta = -1 sign flip, the equation of motion for G^R_{mn}(t) closes
    linearly with the sum matrix Lambda^{(+)} = Lambda^{(1)} + Lambda^{(2)} (LDDL Eq. 15)[cite: 4]:
        d/dt G^R(t) = -i delta(t) I + (-i H - Lambda^{(+)}) G^R(t)
                    = -i delta(t) I + A G^R(t),     where   A = -i H - Lambda^{(+)}

    Diagonalizing the M x M matrix A = V diag(lambda_1, ..., lambda_M) V^{-1} gives the
    exact real-time retarded dot Green's function (the (0, 0) matrix element of exp(A t))[cite: 73]:
        G^R_{dd}(t) = -i theta(t) (sum_{k=1}^{M} : V_{0, k} (V^{-1})_{k, 0} exp(lambda_k t))

    Parameters
    ----------
    solver : LyapunovSolver
        Solver holding the tight-binding baths[cite: 66, 73].
    eps_d : float
        Impurity energy level eps_d[cite: 73].
    t_grid : np.ndarray, shape (N_t,)
        Real-time points t >= 0 at which to evaluate G^R_{dd}(t)[cite: 73].

    Returns
    -------
    G_ret_t : np.ndarray (complex), shape (N_t,)
        Real-time retarded Green's function G^R_{dd}(t)[cite: 73].
    """
    _, A, _, _ = solver.build_matrices(eps_d)
    eigvals, V = linalg.eig(A)
    V_inv = linalg.inv(V)
    # Spectral weights w_k = V_{0, k} * (V^{-1})_{k, 0} satisfying sum_{k=1}^{M} : w_k = 1
    weights = V[0, :] * V_inv[:, 0]
    t_pos = np.asarray(t_grid, dtype=float)
    exp_matrix = np.exp(np.outer(t_pos, eigvals))
    G_ret_t = -1j * (exp_matrix @ weights)
    G_ret_t[t_pos < 0.0] = 0.0
    return G_ret_t


def fourier_transform_qrt_to_spectral(
    t_grid: np.ndarray,
    G_ret_t: np.ndarray,
    omega: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Fourier transform the real-time QRT retarded Green's function G^R_{dd}(t)
    into frequency space to obtain G^R(w) and A(eps_d; w) (LDDL Eq. 7d)[cite: 3, 73]:
        G^R(w) = int_{0}{t_max} : exp(i w t) G^R_{dd}(t) dt
        A(eps_d; w) = -(1 / pi) Im G^R(w)

    Uses composite trapezoidal integration weights (with 1/2 weight at the t = 0
    step discontinuity of theta(t) and at t = t_max)[cite: 73].
    """
    t = np.asarray(t_grid, dtype=float)
    w = np.asarray(omega, dtype=float)
    dt = t[1] - t[0]
    phase = np.exp(1j * np.outer(w, t))
    weights = np.full_like(t, dt)
    weights[0] = 0.5 * dt
    weights[-1] = 0.5 * dt
    G_ret_w = phase @ (G_ret_t * weights)
    A_qrt_w = -(1.0 / np.pi) * np.imag(G_ret_w)
    return G_ret_w, A_qrt_w


