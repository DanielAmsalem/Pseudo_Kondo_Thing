"""
spectral_qrt.py
===============
Step 1c, Step 1a, and Step 1b Spectral & Analytical Reference Module.

WHAT THIS MODULE DOES PHYSICALLY
--------------------------------
This module serves two purposes in our verification pipeline:

1. SOLVING THE DISCRETE TIGHT-BINDING + LINDBLAD MODEL FOR SPECTRAL OBSERVABLES (Step 1c):
   Given a discrete tight-binding bath (or list of baths) generated by `bath.py` with
   mode energies eps_q, dot-bath hopping amplitudes v_q, and Lindblad damping rates gamma_q:
       H = eps_d d^+ d +
           sum_{q=1}^{N} : eps_q c_q^+ c_q +
           sum_{q=1}^{N} : v_q (d^+ c_q + c_q^+ d)
   this module computes:
     (a) The bare discrete-bath retarded self-energy Delta^R_{DL}(w) = Sigma_{DL}(w) - i Gamma_{DL}(w)
         by summing the exact Lindblad-broadened tight-binding propagators (LDDL Eqs. 31a, 42b, 43)[cite: 5, 7, 73]:
             Delta^R_{DL}(w) = sum_{q=1}^{N} : |v_q|^2 / (w - eps_q + i gamma_q)
     (b) The dressed quantum dot retarded Green's function G^R_{dd;DL}(w) and spectral function
         A_{d;DL}(eps_d; w) = -(1/pi) Im G^R_{dd;DL}(w) in frequency space (LDDL Eqs. 17, 50a)[cite: 4, 9, 73].
     (c) The real-time retarded dot propagator G^R_{dd}(t) = -i theta(t) <{d(t), d^+(0)}>_{NESS}
         via the Fermionic Quantum Regression Theorem (QRT, LDDL Eqs. 13-17 & Appendix B)[cite: 4, 18, 19, 20, 73]:
             G^R_{dd}(t) = -i theta(t) [exp(A t)]_{dd},   where   A = -i H - Lambda^{(+)}
         and its Fourier transform back to frequency space:
             G^R(w) = int_{0}{t_max} : exp(i w t) G^R_{dd}(t) dt
         which is the exact real-time protocol that IMEvo performs in Step 2.

2. EVALUATING THE EXACT CONTINUUM ANALYTICAL BENCHMARKS (Steps 1a, 1b, 1c):
   Evaluates all continuum analytical formulas from `PseudoGap-3.pdf` (Eqs. 1-14)[cite: 44, 45, 73]
   using precomputed 64-point and 128-point Gauss-Legendre quadrature with algebraic
   power-law desingularization (zero Fortran QUADPACK calls)[cite: 73].
"""

from __future__ import annotations

from typing import Any, Callable, Optional, Tuple
import numpy as np
from scipy import linalg
from bath import Bath

# ============================================================================
# Precomputed Gauss-Legendre Quadrature Nodes & Weights on [0, 1]
# ============================================================================
# Standard Gauss-Legendre quadrature is defined on [-1, 1]. We shift and scale
# the nodes s_k and weights w_k onto [0, 1] via s -> 0.5 * (s + 1), w -> 0.5 * w
# so that any integral on [0, L] is evaluated as:
#     int_{0}{L} : f(x) dx  =  L * (sum_{k=1}^{N_GL} : w_k f(L * s_k))
_GL64_S, _GL64_W = np.polynomial.legendre.leggauss(64)
_GL64_S = 0.5 * (_GL64_S + 1.0)
_GL64_W = 0.5 * _GL64_W

_GL128_S, _GL128_W = np.polynomial.legendre.leggauss(128)
_GL128_S = 0.5 * (_GL128_S + 1.0)
_GL128_W = 0.5 * _GL128_W


