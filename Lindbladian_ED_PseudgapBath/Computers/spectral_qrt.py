def continuum_self_energy_infinite_D(omega: np.ndarray | float, Gamma0: float, r: float) -> np.ndarray:
    """
    Note Eq. (4): Exact Kramers-Kronig real part of the self-energy in the infinite-bandwidth
    limit D -> infty for -1 < r < 1[cite: 44, 73]:
        Sigma_infty(w) = P int_{-infty}{infty} : (Gamma_0 |w'|^r / (pi (w - w'))) dw'
                       = -sign(w) Gamma_0 |w|^r tan(pi r / 2)
    """
    w = np.asarray(omega, dtype=float)
    if np.isclose(r, 0.0):
        return np.zeros_like(w)
    with np.errstate(divide="ignore", invalid="ignore"):
        mag = np.where(np.abs(w) == 0.0, 0.0, np.power(np.abs(w), r))
    return -np.sign(w) * Gamma0 * mag * np.tan(0.5 * np.pi * r)


def continuum_self_energy_finite_D(
    omega: np.ndarray | float,
    Gamma0: float,
    r: float,
    D: float,
) -> np.ndarray | float:
    """
    Exact Kramers-Kronig real part Sigma_D(w) for a power-law bath with a finite UV
    bandwidth cutoff [-D, +D] (\Gamma(w') = Gamma_0 |w'|^r Theta(D - |w'|))[cite: 73]:
        Sigma_D(w) = P int_{-D}{D} : (Gamma_0 |w'|^r / (pi (w - w'))) dw'

    Mathematical & Numerical Procedure
    ----------------------------------
    For |w| < D, we split the integral on [-D, +D] into the infinite-bandwidth integral
    on (-infty, +infty) minus the regular UV tail integral on |w'| > D:
        Sigma_D(w) = Sigma_infty(w) - (2 Gamma_0 w / pi) * (int_{D}{infty} : ((w')^r / (w^2 - (w')^2)) dw')

    In the UV tail integral, substituting u = D / w' maps [D, infty) onto [0, 1]:
        int_{D}{infty} : ((w')^r / (w^2 - (w')^2)) dw' = -D^{r-1} * (int_{0}{1} : (u^{-r} / (1 - (w/D)^2 u^2)) du)

    For 0 < r < 1 (especially r = +0.9), u^{-r} has an integrable singularity at u -> 0+.
    We remove this singularity analytically via the power-law change of variables:
        u = s^{1/(1-r)}   ===>   u^{-r} du = (1 / (1 - r)) ds
    which transforms the UV tail integral into a completely smooth integral on [0, 1][cite: 73]:
        int_{0}{1} : (u^{-r} / (1 - (w/D)^2 u^2)) du = (1 / (1 - r)) * (int_{0}{1} : (1 / (1 - (w/D)^2 s^{2/(1-r)})) ds)
    evaluated to machine precision using 64-point Gauss-Legendre quadrature[cite: 73].
    """
    w_arr = np.atleast_1d(np.asarray(omega, dtype=float))
    sig_inf = continuum_self_energy_infinite_D(w_arr, Gamma0, r)
    out = np.copy(sig_inf)

    mask = (np.abs(w_arr) > 0.0) & (np.abs(w_arr) < 0.9995 * D)
    if np.any(mask):
        w_in = w_arr[mask]
        ratio2 = (w_in / D) ** 2
        u2_nodes = _GL64_S ** (2.0 / (1.0 - r))
        integrand_mat = 1.0 / (1.0 - np.outer(ratio2, u2_nodes))
        tail_int = (integrand_mat @ _GL64_W) / (1.0 - r)
        uv_correction = -(2.0 * Gamma0 * w_in / np.pi) * (D ** (r - 1.0)) * tail_int
        out[mask] = sig_inf[mask] - uv_correction

    return out if np.ndim(omega) > 0 else float(out[0])


def continuum_self_energy_ir_finite_D(
    omega: np.ndarray,
    Gamma0: float,
    r: float,
    D: float,
    omega_ir: float,
) -> np.ndarray:
    """
    Exact Kramers-Kronig real part Sigma(w) for an IR-regularized power-law bath
        Gamma_{PG}(w) = Gamma_0 (w^2 + omega_{IR}^2)^{r/2} Theta(D - |w|)
    evaluated via the exact non-singular subtracted Hilbert identity[cite: 73]:
        Sigma(w) = (2 w / pi) * (int_{0}{D} : ((Gamma_{PG}(w') - Gamma_{PG}(w)) / (w^2 - (w')^2)) dw')
                   + (Gamma_{PG}(w) / pi) ln|(D - w) / (D + w)|
    Because Gamma_{PG}(w) is smooth at w = 0, Sigma(w) vanishes linearly (~ -w) for |w| << omega_{IR}.
    """
    w_arr = np.atleast_1d(np.asarray(omega, dtype=float))
    s_nodes = _GL128_S
    w_prime = D * (s_nodes ** 2)
    dw_prime = 2.0 * D * s_nodes * _GL128_W

    gam_wp = Gamma0 * ((w_prime ** 2 + omega_ir ** 2) ** (0.5 * r))
    gam_w = Gamma0 * ((w_arr ** 2 + omega_ir ** 2) ** (0.5 * r))

    diff_num = gam_wp[None, :] - gam_w[:, None]
    diff_den = (w_arr[:, None] ** 2) - (w_prime[None, :] ** 2)

    with np.errstate(divide="ignore", invalid="ignore"):
        ratio = np.where(np.abs(diff_den) > 1e-14, diff_num / diff_den, 0.0)

    integral_part = (2.0 * w_arr / np.pi) * (ratio @ dw_prime)
    w_clip = np.clip(w_arr, -0.9999 * D, 0.9999 * D)
    log_part = (gam_w / np.pi) * np.log(np.abs((D - w_clip) / (D + w_clip)))
    return integral_part + log_part


def continuum_spectral_function(
    eps_d: float,
    omega: np.ndarray | float,
    Gamma0: float,
    r: float,
    D: Optional[float] = None,
) -> np.ndarray:
    """
    Note Eq. (1): Continuum dot spectral function A(eps_d; w)[cite: 44, 73]:
        A(eps_d; w) = (1 / pi) * Gamma(w) / ((w - eps_d - Sigma(w))^2 + Gamma(w)^2)
    If `D` is provided, uses the finite-bandwidth self-energy Sigma_D(w); otherwise uses Sigma_infty(w)[cite: 73].
    """
    w = np.asarray(omega, dtype=float)
    with np.errstate(divide="ignore", invalid="ignore"):
        gam = Gamma0 * np.where(np.abs(w) == 0.0, 0.0 if r > 0 else np.inf, np.power(np.abs(w), r))
    if D is not None:
        gam = np.where(np.abs(w) <= D, gam, 0.0)
        sig = continuum_self_energy_finite_D(w, Gamma0, r, D)
    else:
        sig = continuum_self_energy_infinite_D(w, Gamma0, r)

    denom = (w - eps_d - sig) ** 2 + gam ** 2
    with np.errstate(divide="ignore", invalid="ignore"):
        A = np.where(denom > 0.0, (1.0 / np.pi) * gam / denom, 0.0)
    return A


def analytic_S_eps_d(
    eps_d: float,
    T: float,
    Gamma0: float,
    r: float,
    D: Optional[float] = None,
    eps_max: Optional[float] = None,
) -> float:
    """
    Note Eq. (5): Exact single-bath continuum Maxwell entropy integral S(eps_d)[cite: 44, 73]:
        S(eps_d) = -int_{-eps_max}{eps_d} : (dN(eps_d', T) / dT) deps_d'
                 = -int_{-D}{D} : (df(w; T) / dT) * H_phase(eps_d; w) dw
    where the analytically integrated arctan phase factor is:
        H_phase(eps_d; w) = (1 / pi) [ arctan((eps_d - w + Sigma(w)) / Gamma(w))
                                     - arctan((-eps_max - w + Sigma(w)) / Gamma(w)) ]
    (or 1/2 + (1/pi) arctan((eps_d - w + Sigma(w)) / Gamma(w)) when eps_max is None, i.e., eps_max -> infty)[cite: 44, 73].
    Changing variables to the dimensionless thermal frequency x = w / T and folding onto x > 0 gives:
        S(eps_d) = int_{0}{x_max} : (x / ((1 + exp(x))(1 + exp(-x)))) * [ H_phase(eps_d; -x T) - H_phase(eps_d; +x T) ] dx
    """
    x_max = 40.0 if D is None else min(40.0, 0.999 * D / T)
    x_nodes = x_max * _GL128_S
    dx_weights = x_max * _GL128_W

    emx = np.exp(-x_nodes)
    thermal_weight = x_nodes * emx / ((1.0 + emx) ** 2)

    def phase_vec(w_vec: np.ndarray) -> np.ndarray:
        gam = Gamma0 * (np.abs(w_vec) ** r)
        sig = (
            continuum_self_energy_finite_D(w_vec, Gamma0, r, D)
            if D is not None
            else continuum_self_energy_infinite_D(w_vec, Gamma0, r)
        )
        upper = np.arctan((eps_d - w_vec + sig) / gam) / np.pi
        if eps_max is None:
            return 0.5 + upper
        lower = np.arctan((-eps_max - w_vec + sig) / gam) / np.pi
        return upper - lower

    diff_phase = phase_vec(-x_nodes * T) - phase_vec(x_nodes * T)
    return float(np.sum(thermal_weight * diff_phase * dx_weights))


def analytic_S0_note_eq7(T: float, Gamma0: float, r: float) -> float:
    """
    Note Eq. (6) [Eq. 7 in initial note]: Single-bath resonance entropy S(eps_d = 0)
    in the idealized infinite-bandwidth (D -> infty) and infinite gate-sweep (eps_max -> infty) limit[cite: 44, 73]:
        S(0) = (2 / pi) * (int_{0}{infty} : (x / ((1 + exp(x))(1 + exp(-x)))) * arctan(tan(pi r / 2) + (x T)^{1-r} / Gamma_0) dx)
    Limits for -1 < r < 1[cite: 44]:
      - Low-T limit  (T -> 0,     (x T)^{1-r} << Gamma_0): S(0) -> r ln 2
      - High-T limit (T -> infty, (x T)^{1-r} >> Gamma_0): S(0) -> ln 2
    """
    tan_pr2 = np.tan(0.5 * np.pi * r)
    x_max = 45.0
    x_nodes = x_max * _GL128_S
    dx_weights = x_max * _GL128_W

    emx = np.exp(-x_nodes)
    weight = x_nodes * emx / ((1.0 + emx) ** 2)
    arg = tan_pr2 + ((x_nodes * T) ** (1.0 - r)) / Gamma0
    return float((2.0 / np.pi) * np.sum(weight * np.arctan(arg) * dx_weights))


