"""
spectral_qrt.py
===============
Step 1c, Step 1a, and Step 1b Spectral & Analytical Reference Module.

WHAT THIS MODULE DOES PHYSICALLY
--------------------------------
This module serves two purposes in our verification pipeline:

1. SOLVING THE DISCRETE TIGHT-BINDING + LINDBLAD MODEL FOR SPECTRAL & ENTROPY OBSERVABLES:
   Given a discrete tight-binding bath (or list of baths) generated by `bath.py` with
   mode energies eps_q, dot-bath hopping amplitudes v_q, and Lindblad damping rates gamma_q:
       H = eps_d d^+ d +
           sum_{q=1}^{N} : eps_q c_q^+ c_q +
           sum_{q=1}^{N} : v_q (d^+ c_q + c_q^+ d)
   this module computes:
     (a) The bare discrete-bath retarded self-energy Delta^R_{DL}(w) = Sigma_{DL}(w) - i Gamma_{DL}(w)
         by summing the Lindblad-broadened tight-binding propagators (LDDL Eqs. 31a, 42b, 43):
             Delta^R_{DL}(w) = sum_{q=1}^{N} : |v_q|^2 / (w - eps_q + i gamma_{eff}(w, eps_q))
         with frequency-local tail capping so distant UV modes near |eps_q| ~ D do not leak
         1/eps_q^2 Lorentzian tails into the low-energy pseudogap at |w| << D (LDDL Appendix A).
     (b) The dressed quantum dot retarded Green's function G^R_{dd;DL}(w) and spectral function
         A_{d;DL}(eps_d; w) = -(1/pi) Im G^R_{dd;DL}(w) in frequency space (LDDL Eqs. 17, 50a).
     (c) The real-time retarded dot propagator G^R_{dd}(t) = -i theta(t) <{d(t), d^+(0)}>_{NESS}
         via the Fermionic Quantum Regression Theorem (QRT, LDDL Eqs. 13-17 & Appendix B):
             G^R_{dd}(t) = -i theta(t) [exp(A t)]_{dd},   where   A = -i H - Lambda^{(+)}
         and its Fourier transform back to frequency space:
             G^R(w) = int_{0}{t_max} : exp(i w t) G^R_{dd}(t) dt
         which is the exact real-time protocol that IMEvo performs in Step 2.
     (d) The exact discrete tight-binding Maxwell entropy S_{DL}(eps_d) integrated across the
         full thermal frequency window (including the out-of-band tight-binding bound-state
         poles at |w| > D_bath) so that S_{DL}(0) -> ln 2 as T -> infty for any bath cutoff.

2. EVALUATING THE EXACT CONTINUUM ANALYTICAL BENCHMARKS (Steps 1a, 1b, 1c):
   Evaluates all continuum analytical formulas from `PseudoGap-3.pdf` (Eqs. 1-14)
   using precomputed 64-point and 128-point Gauss-Legendre quadrature with algebraic
   power-law desingularization (zero Fortran QUADPACK calls), including the exact
   out-of-band bound-state pole contributions for |w| > D so that the high-temperature
   limit S(0) -> ln 2 is recovered without artificial cutoff drooping.
"""

from __future__ import annotations

from typing import Any, Callable, Optional, Tuple
import numpy as np
from scipy import linalg
from bath import Bath

# ============================================================================
# Precomputed Gauss-Legendre Quadrature Nodes & Weights on [0, 1]
# ============================================================================
# Standard Gauss-Legendre quadrature is defined on [-1, 1]. We shift and scale
# the nodes s_k and weights w_k onto [0, 1] via s -> 0.5 * (s + 1), w -> 0.5 * w
# so that any integral on [0, L] is evaluated as:
#     int_{0}{L} : f(x) dx  =  L * (sum_{k=1}^{N_GL} : w_k f(L * s_k))
_GL64_S, _GL64_W = np.polynomial.legendre.leggauss(64)
_GL64_S = 0.5 * (_GL64_S + 1.0)
_GL64_W = 0.5 * _GL64_W

_GL128_S, _GL128_W = np.polynomial.legendre.leggauss(128)
_GL128_S = 0.5 * (_GL128_S + 1.0)
_GL128_W = 0.5 * _GL128_W


# ============================================================================
# 1. Discrete Tight-Binding LDDL & QRT Spectral Functions (Step 1c & Step 1a)
# ============================================================================

def bare_bath_hybridization_dl(bath: Bath, omega: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
    """
    Solve for the bare retarded self-energy Delta^R_{alpha;DL}(w) of a single discretized
    tight-binding bath decoupled from the dot (LDDL Eqs. 31a, 42b, 43 & Appendix A).

    Physical & Mathematical Procedure
    ---------------------------------
    For a discrete tight-binding mode q with on-site energy eps_q, dot-bath hopping v_q,
    and bin width delta_q, the bare retarded Green's function of mode q is (LDDL Eq. 42b):
        g^R_{qq;DL}(w) = 1 / (w - eps_q + i gamma_{eff}(w, eps_q))

    Why Frequency-Local Broadening gamma_{eff}(w, eps_q) Is Essential for r > 0
    ---------------------------------------------------------------------------
    On a hybrid logarithmic-linear grid (`log_linear`), high-energy bins near |eps_q| ~ D
    have widths delta_q ~ D * ln(Lambda) that are orders of magnitude wider than the
    low-energy linear bin spacing delta. If a high-energy mode q is given a fixed wide
    Lorentzian width gamma_q = c_gamma * delta_q at all frequencies w, its 1/eps_q^2
    Lorentzian tail leaks a spurious constant background into w -> 0 (LDDL Appendix A):
        Gamma_{leak}(0) = sum_{q=1}^{N} : |v_q|^2 gamma_q / eps_q^2
    which swamps the vanishing pseudogap Gamma_0 |w|^r at small |w| for r >= 0.5.
    Conversely, if gamma_q is capped globally at 2 * c_gamma * delta, then at high
    frequencies |w| > D* the Lorentzians are narrower than the bin spacing delta_q.

    Using the frequency-local resolution cap:
        gamma_{eff}(w, eps_q) = min(c_gamma * delta_q, max(gamma_q, c_gamma * |w| * ln(Lambda)))
    ensures that:
      1. Modes resonant with the probed frequency (|eps_q| ~ |w|) always have their full
         local width c_gamma * delta_q, keeping Gamma_{DL}(w) and Sigma_{DL}(w) smooth across
         the entire band [-D, +D].
      2. At low frequencies |w| << D, distant UV modes (|eps_q| ~ D) have their Lorentzian
         tail width bounded by max(gamma_q, c_gamma * |w| * ln(Lambda)) ~ O(delta, |w|),
         completely eliminating the artificial UV tail floor in Gamma_{DL}(w)!

    Parameters
    ----------
    bath : Bath
        Discretized tight-binding Bath object containing (epsilons, v, gammas, bin_widths).
    omega : np.ndarray, shape (N_w,)
        Frequency grid w at which to evaluate Sigma_{DL}(w) and Gamma_{DL}(w).

    Returns
    -------
    re_delta : np.ndarray, shape (N_w,)
        Real part Sigma_{alpha;DL}(w) = Re Delta^R_{alpha;DL}(w) (discrete Kramers-Kronig shift).
    gamma_dl : np.ndarray, shape (N_w,)
        Negative imaginary part Gamma_{alpha;DL}(w) = -Im Delta^R_{alpha;DL}(w) (broadened DOS).
    """
    w = np.asarray(omega, dtype=float)
    re_delta = np.zeros_like(w)
    gamma_dl = np.zeros_like(w)

    log_lam = np.log(bath.Lambda) if (bath.discretization != "linear" and bath.Lambda > 1.0) else 0.0
    w_loc_cap = bath.c_gamma * np.maximum(bath.delta, np.abs(w) * log_lam)

    chunk_size = 1000
    for start in range(0, bath.n_modes, chunk_size):
        end = min(bath.n_modes, start + chunk_size)
        diff = w[:, None] - bath.epsilons[None, start:end]
        gam_adapt = bath.c_gamma * bath.bin_widths[None, start:end]
        gam_base = bath.gammas[None, start:end]
        gam = np.minimum(gam_adapt, np.maximum(gam_base, w_loc_cap[:, None]))
        v2 = (bath.v[None, start:end]) ** 2
        denom = diff * diff + gam * gam
        re_delta += np.sum(v2 * diff / denom, axis=1)
        gamma_dl += np.sum(v2 * gam / denom, axis=1)

    return re_delta, gamma_dl


def dot_spectral_function_dl_freq(
    solver: Any,
    eps_d: float,
    omega: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Compute the dressed dot retarded Green's function G^R_{dd;DL}(w) and dot spectral
    function A_{d;DL}(eps_d; w) directly in frequency space (LDDL Eqs. 17, 50a):
        G^R_{dd;DL}(w) = 1 / (w - eps_d - sum_{alpha} : Delta^R_{alpha;DL}(w))
                       = 1 / (w - eps_d - Sigma_{tot;DL}(w) + i Gamma_{tot;DL}(w))
        A_{d;DL}(eps_d; w) = -(1 / pi) Im G^R_{dd;DL}(w)
    """
    w = np.asarray(omega, dtype=float)
    re_tot = np.zeros_like(w)
    im_tot = np.zeros_like(w)
    for b in solver.baths:
        re_b, gam_b = bare_bath_hybridization_dl(b, w)
        re_tot += re_b
        im_tot -= gam_b  # Im Delta^R = -Gamma

    G_ret = 1.0 / (w - eps_d - re_tot - 1j * im_tot)
    A_dl = -(1.0 / np.pi) * np.imag(G_ret)
    return G_ret, A_dl


def dot_retarded_gf_qrt_time(
    solver: Any,
    eps_d: float,
    t_grid: np.ndarray,
) -> np.ndarray:
    """
    Compute the real-time retarded dot Green's function G^R_{dd}(t) using the
    Fermionic Quantum Regression Theorem (LDDL Sec. II B Eqs. 13-17 & Appendix B):
        d/dt G^R(t) = -i delta(t) I + (-i H - Lambda^{(+)}) G^R(t)
                    = -i delta(t) I + A G^R(t),     where   A = -i H - Lambda^{(+)}
        G^R_{dd}(t) = -i theta(t) (sum_{k=1}^{M} : V_{0, k} (V^{-1})_{k, 0} exp(lambda_k t))
    """
    _, A, _, _ = solver.build_matrices(eps_d)
    eigvals, V = linalg.eig(A)
    V_inv = linalg.inv(V)
    weights = V[0, :] * V_inv[:, 0]
    t_pos = np.asarray(t_grid, dtype=float)
    exp_matrix = np.exp(np.outer(t_pos, eigvals))
    G_ret_t = -1j * (exp_matrix @ weights)
    G_ret_t[t_pos < 0.0] = 0.0
    return G_ret_t


def fourier_transform_qrt_to_spectral(
    t_grid: np.ndarray,
    G_ret_t: np.ndarray,
    omega: np.ndarray,
) -> Tuple[np.ndarray, np.ndarray]:
    """
    Fourier transform the real-time QRT retarded Green's function G^R_{dd}(t)
    into frequency space to obtain G^R(w) and A(eps_d; w) (LDDL Eq. 7d):
        G^R(w) = int_{0}{t_max} : exp(i w t) G^R_{dd}(t) dt
        A(eps_d; w) = -(1 / pi) Im G^R(w)
    """
    t = np.asarray(t_grid, dtype=float)
    w = np.asarray(omega, dtype=float)
    dt = t[1] - t[0]
    phase = np.exp(1j * np.outer(w, t))
    weights = np.full_like(t, dt)
    weights[0] = 0.5 * dt
    weights[-1] = 0.5 * dt
    G_ret_w = phase @ (G_ret_t * weights)
    A_qrt_w = -(1.0 / np.pi) * np.imag(G_ret_w)
    return G_ret_w, A_qrt_w


def tight_binding_S_eps_d(
    bath: Bath,
    eps_d: float | np.ndarray,
    T: float,
    eps_max: Optional[float] = None,
    include_out_of_band_poles: bool = True,
) -> Tuple[np.ndarray, np.ndarray] | float:
    """
    Evaluate the exact single-bath Maxwell derivative dn_d / dT and entropy S_{DL}(eps_d)
    of the discrete N-mode tight-binding bath across the full thermal frequency window:
        dn_d(eps_d) / dT = int_{-infty}{infty} : (df(w; T) / dT) * A_{d;DL}(eps_d; w) dw
        S_{DL}(eps_d) = -int_{-infty}{infty} : (df(w; T) / dT)
                        * (1 / pi) [ arctan((eps_d - w + Sigma_{DL}(w)) / Gamma_{DL}(w))
                                   - arctan((-eps_max - w + Sigma_{DL}(w)) / Gamma_{DL}(w)) ] dw

    Why This Recovers S_{DL}(0) -> ln 2 at High T Without Drooping
    --------------------------------------------------------------
    1. Inside the tight-binding bath band (|w| <= D_bath): uses the exact discrete
       tight-binding self-energies Sigma_{DL}(w) and Gamma_{DL}(w) summed over all N_modes
       discrete modes in `bath`.
    2. Outside the tight-binding bath band (|w| > D_bath): when T >= D_bath / 5, sweeping
       the dot energy eps_d' from -eps_max (~ -50 T) to 0 sweeps across the out-of-band
       regime |eps_d'| > D_bath where the discrete tight-binding Hamiltonian H(eps_d')
       has a sharp bound-state pole at w - eps_d' - Sigma_{DL}(w) = 0 with Gamma_{DL}(w) -> 0^+.
       Retaining the |w| > D_bath panel (`include_out_of_band_poles=True`) captures this
       bound-state occupation and guarantees S_{DL}(0) -> ln 2 as T -> infty for any D_bath!
    """
    ed_arr = np.atleast_1d(np.asarray(eps_d, dtype=float))
    D_bath = bath.D
    x_full_max = 45.0
    p = 2.0 - max(bath.r, 0.0)

    def eval_panel(x_nodes: np.ndarray, dx_weights: np.ndarray, in_band: bool) -> Tuple[np.ndarray, np.ndarray]:
        w_pos = x_nodes * T
        emx = np.exp(-x_nodes)
        thermal_weight = x_nodes * emx / ((1.0 + emx) ** 2)

        sig_pos, gam_pos = bare_bath_hybridization_dl(bath, w_pos)
        # By particle-hole symmetry of the symmetric tight-binding bath:
        # Sigma_{DL}(-w) = -Sigma_{DL}(+w) and Gamma_{DL}(-w) = +Gamma_{DL}(+w)
        sig_neg = -sig_pos
        gam_neg = gam_pos

        def phase_and_lorentz(w_vec: np.ndarray, sig_vec: np.ndarray, gam_vec: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
            num_upper = ed_arr[:, None] - w_vec[None, :] + sig_vec[None, :]
            if in_band:
                gam_safe = np.maximum(gam_vec[None, :], 1e-16)
                upper = np.arctan(num_upper / gam_safe) / np.pi
                lorentz = (1.0 / np.pi) * gam_safe / (num_upper * num_upper + gam_safe * gam_safe)
            else:
                upper = 0.5 * np.sign(num_upper)
                lorentz = np.zeros_like(num_upper)

            if eps_max is None:
                return 0.5 + upper, lorentz

            num_lower = -eps_max - w_vec[None, :] + sig_vec[None, :]
            if in_band:
                gam_safe = np.maximum(gam_vec[None, :], 1e-16)
                lower = np.arctan(num_lower / gam_safe) / np.pi
            else:
                lower = 0.5 * np.sign(num_lower)
            return upper - lower, lorentz

        ph_neg, lor_neg = phase_and_lorentz(-w_pos, sig_neg, gam_neg)
        ph_pos, lor_pos = phase_and_lorentz(+w_pos, sig_pos, gam_pos)

        S_part = (ph_neg - ph_pos) @ (thermal_weight * dx_weights)
        dn_dT_part = ((lor_pos - lor_neg) @ (thermal_weight * dx_weights)) / T
        return dn_dT_part, S_part

    # Panel 1: In-band tight-binding modes x in [0, min(45, 0.9999 * D_bath / T)]
    x_cut = min(x_full_max, 0.9999 * D_bath / T)
    x1 = x_cut * (_GL128_S ** (1.0 / p))
    dx1 = (x_cut / p) * (_GL128_S ** (1.0 / p - 1.0)) * _GL128_W
    dn_dT_tot, S_tot = eval_panel(x1, dx1, in_band=True)

    # Panel 2: Out-of-band tight-binding bound-state poles x in [1.0001 * D_bath / T, 45.0]
    if include_out_of_band_poles and (1.0001 * D_bath / T < x_full_max):
        x_start = 1.0001 * D_bath / T
        span = x_full_max - x_start
        x2 = x_start + span * _GL128_S
        dx2 = span * _GL128_W
        dn2, S2 = eval_panel(x2, dx2, in_band=False)
        dn_dT_tot = dn_dT_tot + dn2
        S_tot = S_tot + S2

    if np.ndim(eps_d) == 0:
        return float(S_tot[0])
    return dn_dT_tot, S_tot


